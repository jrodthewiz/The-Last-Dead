import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '..');
const [sourceArg, outputArg] = process.argv.slice(2);
const sourcePath = path.resolve(projectRoot, sourceArg || 'docs/story-map-art/black-gullet-blockout-factory.ts');
const outputPath = path.resolve(projectRoot, outputArg || 'assets/models/black-gullet-procedural.js');

if (typeof stripTypeScriptTypes !== 'function') {
  throw new Error('This source conversion step needs Node.js 23.11 or newer; the game runtime remains plain JavaScript.');
}

const original = await readFile(sourcePath, 'utf8');
const lookDevStart = original.indexOf('\nexport function createBlackGulletStoryThresholdLookDevLights(');
if (lookDevStart < 0) throw new Error(`Could not locate the end of the runtime model factory in ${sourcePath}`);

let omittedAttachmentGeometry = 0;
const modelFactory = original.slice(0, lookDevStart)
  .replace(/^import\s+.*?;\s*$/gm, '')
  // Keep authored attachment contracts in userData, but use each part's authored mesh.
  // The factory otherwise substitutes straight cylinders for any component with sockets,
  // which erases the extruded arch profiles and curved cable geometry.
  .replace(/^(  const attachment_[\w]+ = )\{[^;\r\n]*\};$/gm, (_match, prefix) => {
    omittedAttachmentGeometry += 1;
    return `${prefix}null;`;
  });
const vendorPath = path.relative(path.dirname(outputPath), path.join(projectRoot, 'vendor/three.module.js')).replaceAll('\\', '/');
const vendorImport = vendorPath.startsWith('.') ? vendorPath : `./${vendorPath}`;
const typeScript = `import * as THREE from '${vendorImport}';\n${modelFactory}`;
const javascript = stripTypeScriptTypes(typeScript, { mode: 'transform' });

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, `// Generated by scripts/build-black-gullet-runtime.mjs from ${path.relative(projectRoot, sourcePath).replaceAll('\\', '/')}\n${javascript}`, 'utf8');
console.log(`Compiled ${path.relative(projectRoot, sourcePath)} -> ${path.relative(projectRoot, outputPath)} (kept ${omittedAttachmentGeometry} semantic attachment contracts; omitted their cylinder substitutes)`);
